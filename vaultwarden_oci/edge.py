def _prepare_vaultwarden_log(path: Path) -> None:
    if path == VAULTWARDEN_LOG:
        from .runtime import VAULTWARDEN_GID, VAULTWARDEN_UID
        uid, gid = VAULTWARDEN_UID, VAULTWARDEN_GID
    else:
        uid, gid = os.geteuid(), os.getegid()
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        os.chown(path.parent, uid, gid)
        os.chmod(path.parent, 0o700)
        descriptor = os.open(
            path,
            os.O_WRONLY | os.O_CREAT | os.O_APPEND | getattr(os, "O_NOFOLLOW", 0),
            0o600,
        )
        os.close(descriptor)
        os.chown(path, uid, gid)
        os.chmod(path, 0o600)
        info = path.lstat()
    except OSError as exc:
        raise EdgeError(f"cannot prepare Vaultwarden CrowdSec log {path}: {exc}") from exc
    if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
        raise EdgeError(f"Vaultwarden CrowdSec log is not a regular file: {path}")



def consume_remediation_start_token(*, path: Path = REMEDIATION_START_TOKEN) -> None:
    try:
        info = path.lstat()
    except FileNotFoundError as exc:
        raise EdgeError("CrowdSec Cloudflare remediation start was not authorized by vwctl") from exc
    except OSError as exc:
        raise EdgeError(f"cannot inspect CrowdSec remediation start token: {exc}") from exc
    if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
        raise EdgeError("CrowdSec Cloudflare remediation start token is not a regular file")
    try:
        path.unlink()
    except OSError as exc:
        raise EdgeError(f"cannot consume CrowdSec remediation start token: {exc}") from exc


def start_remediation(*, paths: EdgePaths = EdgePaths(), runner: Runner = run_command) -> None:
    if os.geteuid() != 0 and paths == EdgePaths():
        raise EdgeError("vwctl crowdsec remediation-start must run as root")
    if _active(BOUNCER_SERVICE, runner):
        raise EdgeError("CrowdSec Cloudflare remediation is already active")
    if not _disabled(BOUNCER_SERVICE, runner):
        raise EdgeError("CrowdSec Cloudflare bouncer must remain disabled at boot; rerun vwctl crowdsec setup")
    _unlink_state(paths.fail_open_confirmation, "CrowdSec Fail Open confirmation")
    try:
        _atomic_write(paths.remediation_start_token, f"{os.getpid()}:{time.time_ns()}\n", 0o600)
    except OSError as exc:
        raise EdgeError(f"cannot authorize CrowdSec remediation start: {exc}") from exc
    result = runner(["systemctl", "start", BOUNCER_SERVICE])
    if not result.ok or not _active(BOUNCER_SERVICE, runner) or paths.remediation_start_token.exists():
        _unlink_state(paths.remediation_start_token, "CrowdSec remediation start token")
        detail = result.kind if result.returncode is None else f"exit {result.returncode}"
        raise EdgeError(f"CrowdSec Cloudflare remediation start failed ({detail})")

    # The start owner also owns proof of what this exact process invocation
    # loaded. A config file that merely looks correct after start is not enough.
    from . import crowdsec_worker_policy

    try:
        crowdsec_worker_policy.attest_current(paths, runner)
    except crowdsec_worker_policy.WorkerPolicyError as exc:
        stopped = runner(["systemctl", "stop", BOUNCER_SERVICE])
        suffix = "" if stopped.ok and not _active(BOUNCER_SERVICE, runner) else "; unproven Worker stop could not be proven"
        raise EdgeError(
            f"CrowdSec Cloudflare remediation started but local-only decision policy could not be proven: {exc}{suffix}"
        ) from exc


def _service_invocation_id(runner: Runner) -> str | None:
    if not _active(BOUNCER_SERVICE, runner):
        return None
    result = runner(["systemctl", "show", BOUNCER_SERVICE, "--property=InvocationID", "--value"])
    value = result.stdout.strip().lower() if result.ok else ""
    if len(value) != 32 or any(char not in "0123456789abcdef" for char in value):
        return None
    return value


def confirm_fail_open(
    *,
    paths: EdgePaths = EdgePaths(),
    runner: Runner = run_command,
    now: int | None = None,
) -> None:
    if os.geteuid() != 0 and paths == EdgePaths():
        raise EdgeError("vwctl crowdsec confirm-fail-open must run as root")
    invocation = _service_invocation_id(runner)
    if invocation is None:
        raise EdgeError("CrowdSec Cloudflare remediation is not active with a valid systemd invocation")
    payload = {
        "schema_version": 1,
        "invocation_id": invocation,
        "confirmed_at": int(time.time()) if now is None else int(now),
    }
    try:
        _atomic_write(
            paths.fail_open_confirmation,
            json.dumps(payload, sort_keys=True, separators=(",", ":")) + "\n",
            0o600,
        )
    except OSError as exc:
        raise EdgeError(f"cannot persist CrowdSec Fail Open confirmation: {exc}") from exc


def _fail_open_confirmed(path: Path, invocation: str | None) -> bool:
    if invocation is None:
        return False
    try:
        info = path.lstat()
        if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
            return False
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (FileNotFoundError, OSError, UnicodeError, json.JSONDecodeError):
        return False
    return (
        isinstance(payload, dict)
        and payload.get("schema_version") == 1
        and payload.get("invocation_id") == invocation
        and isinstance(payload.get("confirmed_at"), int)
        and not isinstance(payload.get("confirmed_at"), bool)
    )


def _iptables_healthy(binary: str, networks: Iterable[ipaddress._BaseNetwork], runner: Runner) -> bool:
    jump = _rule(binary, RULE_COMMENT, CHAIN)
    guard = _rule(binary, GUARD_COMMENT, "DROP")
    if not runner([binary, "-w", "-C", "DOCKER-USER", *jump[2:]]).ok:
        return False
    if runner([binary, "-w", "-C", "DOCKER-USER", *guard[2:]]).ok:
        return False
    listing = runner([binary, "-w", "-S", CHAIN])
    if not listing.ok:
        return False
    expected = [
        ("-A", CHAIN, "-s", str(network), "-j", "RETURN")
        for network in networks
    ]
    expected.append(("-A", CHAIN, "-j", "DROP"))
    try:
        actual = [tuple(shlex.split(line)) for line in listing.stdout.splitlines() if line.startswith(f"-A {CHAIN} ")]
    except ValueError:
        return False
    return actual == expected


def _caddy_trust_configured(caddy_text: str) -> bool:
    return (
        "trusted_proxies cloudflare {" in caddy_text
        and "timeout 15s" in caddy_text
        and "trusted_proxies_strict" in caddy_text
        and "client_ip_headers CF-Connecting-IP" in caddy_text
        and "trusted_proxies static" not in caddy_text
    )


def _caddy_admin_disabled(caddy_text: str) -> bool:
    return "@admin path /admin*" in caddy_text and "respond @admin 404" in caddy_text


def _caddy_admin_protected(caddy_text: str) -> bool:
    if "@admin path /admin*" not in caddy_text:
        return False
    start = caddy_text.find(" handle @admin {")
    if start < 0:
        return False
    end = caddy_text.find(" @auth path", start)
    if end < 0:
        return False
    admin_block = caddy_text[start:end]
    return all(
        marker in admin_block
        for marker in (
            "rate_limit {",
            "zone admin {",
            "key {client_ip}",
            "basic_auth {",
            "admin {env.ADMIN_BASIC_AUTH_HASH}",
        )
    )


def doctor_checks(
    *,
    paths: EdgePaths = EdgePaths(),
    runner: Runner = run_command,
    now: int | None = None,
) -> list[DoctorCheck]:
    checks: list[DoctorCheck] = []
    try:
        caddy_text = CADDYFILE.read_text(encoding="utf-8")
    except (OSError, UnicodeError):
        checks.append(DoctorCheck("edge.caddy.trusted_proxy", "SKIP", "rendered Caddy config is not present; service may be stopped"))
        checks.append(DoctorCheck("edge.admin.protection", "SKIP", "rendered Caddy admin policy is not present; service may be stopped"))
    else:
        trusted = _caddy_trust_configured(caddy_text)
        checks.append(DoctorCheck(
            "edge.caddy.trusted_proxy",
            "PASS" if trusted else "FAIL",
            "Caddy uses strict Cloudflare trusted proxies with a bounded refresh and CF-Connecting-IP" if trusted
            else "Caddy trusted-proxy strictness/timeout/CF-Connecting-IP configuration is missing or duplicated with static CIDRs",
        ))
        admin_disabled = _caddy_admin_disabled(caddy_text)
        admin_gated = _caddy_admin_protected(caddy_text)
        if admin_disabled:
            checks.append(DoctorCheck("edge.admin.protection", "PASS", "Vaultwarden admin route is disabled at Caddy"))
        elif admin_gated and ADMIN_TOKEN_FILE.exists() and ADMIN_HASH_FILE.exists():
            checks.append(DoctorCheck("edge.admin.protection", "PASS", "admin token capability, per-client rate limit, and outer Basic Auth gate are active"))
        else:
            checks.append(DoctorCheck("edge.admin.protection", "FAIL", "admin route is missing Vaultwarden token capability, rate limit, or outer Basic Auth gate"))

    caddy_state = runner(["docker", "container", "inspect", "--format", "{{json .State}}", CADDY_CONTAINER])
    healthy = False
    if caddy_state.ok:
        try:
            state = json.loads(caddy_state.stdout)
            healthy = isinstance(state, dict) and state.get("Status") == "running" and (
                not isinstance(state.get("Health"), dict) or state["Health"].get("Status") == "healthy"
            )
        except (json.JSONDecodeError, TypeError, AttributeError):
            healthy = False
    caddy_absent = (not caddy_state.ok) and "no such" in (caddy_state.stderr + caddy_state.stdout).lower()
    checks.append(DoctorCheck(
        "edge.caddy.health",
        "PASS" if healthy else "SKIP" if caddy_absent else "FAIL",
        "Caddy container is running and healthy" if healthy
        else "Caddy container is not present; service may be stopped" if caddy_absent
        else "Caddy container is stopped, unhealthy, or could not be inspected",
    ))
    policy: CloudflarePolicy | None = None
    try:
        policy = load_lkg(paths.lkg, now=now)
    except EdgeError as exc:
        checks.append(DoctorCheck("edge.cloudflare.cidrs", "FAIL", str(exc)))
    else:
        age = (int(time.time()) if now is None else int(now)) - policy.fetched_at
        checks.append(DoctorCheck("edge.cloudflare.cidrs", "PASS", f"validated Cloudflare last-known-good policy age={max(0, age)}s"))
    if policy is not None and _iptables_healthy("iptables", policy.ipv4, runner) and _iptables_healthy("ip6tables", policy.ipv6, runner):
        checks.append(DoctorCheck("edge.cloudflare.iptables", "PASS", f"Cloudflare-only ORIGINAL-direction Docker 443 policy is complete on {BRIDGE_IFACE}"))
    else:
        checks.append(DoctorCheck("edge.cloudflare.iptables", "FAIL", "Cloudflare Docker 443 policy is missing, guarded, stale, misdirected, or has unexpected rules"))

    if _active(CROWDSEC_SERVICE, runner):
        checks.append(DoctorCheck("crowdsec.engine", "PASS", "CrowdSec Security Engine is active"))
    else:
        checks.append(DoctorCheck("crowdsec.engine", "FAIL", "CrowdSec Security Engine is not active"))

    installed_collections = all(
        runner(["cscli", "collections", "inspect", collection]).ok
        for collection in CROWDSEC_COLLECTIONS
    )
    checks.append(DoctorCheck(
        "crowdsec.hub",
        "PASS" if installed_collections else "FAIL",
        "Caddy, Linux/SSH, iptables/kernel, and Vaultwarden detection collections are installed"
        if installed_collections
        else "required CrowdSec detection collections are incomplete",
    ))

    firewall_bouncer = runner(["cscli", "bouncers", "inspect", FIREWALL_BOUNCER_ID, "-o", "json"])
    firewall_ok = (
        _active(FIREWALL_BOUNCER_SERVICE, runner)
        and _enabled(FIREWALL_BOUNCER_SERVICE, runner)
        and firewall_bouncer.ok
        and _firewall_boundary_healthy(paths, runner, require_live=True)
    )
    checks.append(DoctorCheck(
        "crowdsec.firewall",
        "PASS" if firewall_ok else "FAIL",
        "CrowdSec firewall bouncer effective config and live nftables ownership are host INPUT only"
        if firewall_ok
        else "CrowdSec host-input firewall remediation service/LAPI/effective-config/live-nftables state is unhealthy or not INPUT-only",
    ))

    active = _active(BOUNCER_SERVICE, runner)
    disabled = _disabled(BOUNCER_SERVICE, runner)
    config_test = runner([BOUNCER_BINARY, "-c", str(paths.remediation_config), "-t"])
    bouncer = runner(["cscli", "bouncers", "inspect", BOUNCER_ID, "-o", "json"])
    invocation = _service_invocation_id(runner) if active else None
    confirmed = _fail_open_confirmed(paths.fail_open_confirmation, invocation)
    if active and disabled and config_test.ok and bouncer.ok and confirmed:
        checks.append(DoctorCheck("crowdsec.cloudflare", "PASS", "Cloudflare Worker bouncer is active, boot-disabled, and Fail Open is operator-confirmed for this invocation"))
    elif active and disabled and config_test.ok and bouncer.ok:
        checks.append(DoctorCheck("crowdsec.cloudflare", "FAIL", "Cloudflare Worker bouncer is active but Fail Open is not confirmed for this service invocation"))
    else:
        checks.append(DoctorCheck("crowdsec.cloudflare", "FAIL", "CrowdSec Cloudflare remediation service/config/LAPI state is unhealthy or not explicitly armed"))

    # Keep the source-policy proof in the canonical doctor owner so direct
    # callers and every presentation layer see the same result.
    from . import crowdsec_worker_policy

    return crowdsec_worker_policy.enforce_doctor_checks(
        checks,
        paths=paths,
        runner=runner,
    )

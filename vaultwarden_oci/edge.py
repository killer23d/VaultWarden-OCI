def _download_installer() -> Path:
    text = _http_text(CROWDSEC_REPO_INSTALLER, MAX_INSTALLER_BYTES)
    runtime = Path("/run/vaultwarden-oci/transient")
    runtime.mkdir(parents=True, exist_ok=True)
    descriptor, name = tempfile.mkstemp(prefix="crowdsec-repo-", suffix=".sh", dir=runtime)
    path = Path(name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(path, 0o700)
        return path
    except Exception:
        path.unlink(missing_ok=True)
        raise


def _has_noncomment_content(path: Path) -> bool:
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return False
    except (OSError, UnicodeError) as exc:
        raise EdgeError(f"cannot inspect CrowdSec acquisition {path}: {exc}") from exc
    return any(line.strip() and not line.lstrip().startswith("#") for line in text.splitlines())


def _is_cscli_setup_acquisition(path: Path) -> bool:
    if not path.name.startswith("setup.") or path.suffix.lower() not in {".yaml", ".yml"}:
        return False
    try:
        info = path.lstat()
        if not stat.S_ISREG(info.st_mode):
            return False
        lines = path.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError:
        return False
    except (OSError, UnicodeError) as exc:
        raise EdgeError(f"cannot inspect CrowdSec generated acquisition {path}: {exc}") from exc

    header: list[str] = []
    checksums: list[str] = []
    content_start: int | None = None
    for index, line in enumerate(lines):
        if not line.startswith("#") and line.strip():
            content_start = index
            break
        header.append(line)
        if line.startswith(CSCLI_CHECKSUM_PREFIX):
            checksums.append(line[len(CSCLI_CHECKSUM_PREFIX):].strip())

    if CSCLI_SETUP_MARKER not in header or len(checksums) != 1:
        return False
    checksum = checksums[0]
    if (
        len(checksum) != 32
        or any(char not in "0123456789abcdef" for char in checksum)
        or content_start is None
    ):
        return False

    # Match CrowdSec clisetup.VerifyChecksum: the generated header is excluded,
    # the remaining lines are normalized to LF, and the declared value must be
    # a prefix of the SHA-256 digest of that exact remainder.
    content = ("\n".join(lines[content_start:]) + "\n").encode("utf-8")
    return hashlib.sha256(content).hexdigest().startswith(checksum)


def _remove_cscli_setup_acquisitions(paths: EdgePaths) -> None:
    directory = paths.acquisition.parent
    try:
        entries = sorted(directory.iterdir(), key=lambda entry: entry.name)
    except FileNotFoundError:
        return
    except OSError as exc:
        raise EdgeError(f"cannot inspect CrowdSec acquisition directory {directory}: {exc}") from exc
    for entry in entries:
        if entry == paths.acquisition or not _is_cscli_setup_acquisition(entry):
            continue
        try:
            entry.unlink()
        except OSError as exc:
            raise EdgeError(f"cannot remove CrowdSec cscli-generated acquisition {entry}: {exc}") from exc


def _assert_acquisition_scope(paths: EdgePaths) -> None:
    directory = paths.acquisition.parent
    try:
        candidates = sorted(
            (entry for entry in directory.iterdir() if entry.suffix.lower() in {".yaml", ".yml"}),
            key=lambda entry: entry.name,
        )
    except FileNotFoundError:
        directory.mkdir(parents=True, exist_ok=True)
        candidates = []
    except OSError as exc:
        raise EdgeError(f"cannot inspect CrowdSec acquisition directory {directory}: {exc}") from exc
    unexpected = [entry for entry in candidates if entry != paths.acquisition]
    if unexpected:
        names = ", ".join(entry.name for entry in unexpected)
        raise EdgeError(f"unexpected CrowdSec acquisition file(s): {names}")
    if paths == EdgePaths() and _has_noncomment_content(CROWDSEC_ACQUIS_MAIN):
        raise EdgeError(
            "unexpected active CrowdSec /etc/crowdsec/acquis.yaml; "
            "VaultWarden-OCI requires one project-managed acquisition file"
        )


def _unlink_state(path: Path, label: str) -> None:
    try:
        path.unlink(missing_ok=True)
    except OSError as exc:
        raise EdgeError(f"cannot clear {label}: {exc}") from exc


@contextmanager
def _suppress_package_service_starts(path: Path) -> Iterator[None]:
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
    try:
        descriptor = os.open(path, flags, 0o755)
    except FileExistsError as exc:
        raise EdgeError(
            f"cannot safely suppress CrowdSec package service auto-start because {path} already exists; "
            "preserve the host policy and resolve it explicitly before retrying"
        ) from exc
    except OSError as exc:
        raise EdgeError(f"cannot create temporary package service policy {path}: {exc}") from exc
    identity = os.fstat(descriptor)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.write("#!/bin/sh\nexit 101\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(path, 0o755)
        yield
    finally:
        try:
            current = path.lstat()
        except FileNotFoundError:
            current = None
        except OSError as exc:
            raise EdgeError(f"cannot inspect temporary package service policy {path}: {exc}") from exc
        if current is not None:
            if (current.st_dev, current.st_ino) != (identity.st_dev, identity.st_ino):
                raise EdgeError(
                    f"temporary package service policy {path} changed unexpectedly; refusing to remove it"
                )
            try:
                path.unlink()
            except OSError as exc:
                raise EdgeError(f"cannot remove temporary package service policy {path}: {exc}") from exc


def _package_install_env() -> dict[str, str]:
    """Build the isolated apt environment used for CrowdSec packages only."""
    install_env = dict(os.environ)
    install_env["DEBIAN_FRONTEND"] = "noninteractive"
    install_env["CROWDSEC_SETUP_UNATTENDED_DISABLE"] = "1"
    # Current CrowdSec and firewall-bouncer Debian maintainer scripts call
    # systemctl directly. SYSTEMD_OFFLINE makes start/restart no-ops for this
    # child transaction without contaminating later project-owned systemctl.
    install_env["SYSTEMD_OFFLINE"] = "1"
    return install_env


def _service_absent(result: CommandResult) -> bool:
    detail = (result.stdout + "\n" + result.stderr).lower()
    return any(
        marker in detail
        for marker in (
            "does not exist",
            "could not be found",
            "not loaded",
            "no such file",
            "unit file not found",
        )
    )


def _contain_package_bouncers(runner: Runner) -> list[str]:
    """Disable/stop package-owned services before project configuration begins."""
    problems: list[str] = []
    for service, label in (
        (CROWDSEC_SERVICE, "CrowdSec engine"),
        (BOUNCER_SERVICE, "Cloudflare bouncer"),
        (FIREWALL_BOUNCER_SERVICE, "firewall bouncer"),
    ):
        result = runner(["systemctl", "disable", "--now", service])
        if result.ok or _service_absent(result):
            continue
        detail = result.kind if result.returncode is None else f"exit {result.returncode}"
        problems.append(f"{label} disable/stop could not be proven ({detail})")
    return problems


def _parse_hook_list(text: str) -> tuple[str, ...] | None:
    lines = text.splitlines()
    for index, raw in enumerate(lines):
        stripped = raw.strip()
        if not stripped.startswith("nftables_hooks:"):
            continue
        tail = stripped.split(":", 1)[1].strip()
        if tail:
            if not (tail.startswith("[") and tail.endswith("]")):
                return None
            inner = tail[1:-1].strip()
            if not inner:
                return ()
            return tuple(item.strip().strip("\"'") for item in inner.split(","))
        hooks: list[str] = []
        for following in lines[index + 1:]:
            item = following.strip()
            if not item or item.startswith("#"):
                continue
            if not item.startswith("-"):
                break
            value = item[1:].strip().strip("\"'")
            if not value:
                return None
            hooks.append(value)
        return tuple(hooks)
    return None


def _effective_firewall_hooks(paths: EdgePaths, runner: Runner) -> tuple[str, ...] | None:
    result = runner(
        [FIREWALL_BOUNCER_BINARY, "-c", str(_firewall_config_path(paths)), "-T"]
    )
    if not result.ok:
        return None
    return _parse_hook_list(result.stdout)


def _firewall_config_input_only(paths: EdgePaths, runner: Runner) -> bool:
    """Check the merged hook policy without initializing the nftables backend."""
    return _effective_firewall_hooks(paths, runner) == ("input",)


def _nft_table_input_only(
    runner: Runner,
    *,
    family: str,
    table: str,
    chain_base: str,
) -> bool:
    result = runner(["nft", "--json", "list", "table", family, table])
    if not result.ok:
        return False
    try:
        payload = json.loads(result.stdout)
    except (json.JSONDecodeError, TypeError):
        return False
    entries = payload.get("nftables") if isinstance(payload, dict) else None
    if not isinstance(entries, list):
        return False
    hooked_chains: list[tuple[str, str]] = []
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        chain = entry.get("chain")
        if not isinstance(chain, dict):
            continue
        if chain.get("family") != family or chain.get("table") != table:
            continue
        hook = chain.get("hook")
        if hook is None:
            continue
        name = chain.get("name")
        if not isinstance(name, str) or not isinstance(hook, str):
            return False
        hooked_chains.append((name, hook))
    return sorted(hooked_chains) == [(f"{chain_base}-input", "input")]


def _live_firewall_input_only(runner: Runner) -> bool:
    return _nft_table_input_only(
        runner,
        family="ip",
        table="crowdsec",
        chain_base="crowdsec-chain",
    ) and _nft_table_input_only(
        runner,
        family="ip6",
        table="crowdsec6",
        chain_base="crowdsec6-chain",
    )


def _firewall_boundary_healthy(
    paths: EdgePaths,
    runner: Runner,
    *,
    require_live: bool,
) -> bool:
    # firewall-bouncer v0.0.36 initializes its backend before handling -t and
    # tears that backend down on exit. Keep -t strictly pre-start; live proof
    # must be observational so health/doctor checks cannot remove nftables state.
    if not require_live:
        config = _firewall_config_path(paths)
        if not runner([FIREWALL_BOUNCER_BINARY, "-c", str(config), "-t"]).ok:
            return False
    if not _firewall_config_input_only(paths, runner):
        return False
    return not require_live or _live_firewall_input_only(runner)


def _create_lapi_bouncer_key(runner: Runner, bouncer_id: str, label: str) -> str:
    runner(["cscli", "bouncers", "delete", bouncer_id, "--ignore-missing"])
    created = runner(["cscli", "-oraw", "bouncers", "add", bouncer_id])
    key = created.stdout.strip() if created.ok else ""
    if not key or any(char.isspace() for char in key):
        raise EdgeError(f"cannot create CrowdSec LAPI credential for {label}")
    return key


def _local_lapi_url(runner: Runner) -> str:
    result = runner(["cscli", "config", "show", "-oraw", "--key", "Config.API.Server.ListenURI"])
    raw = result.stdout.strip() if result.ok else ""
    if not raw:
        return DEFAULT_LAPI_URL
    if raw.startswith(":"):
        raw = "127.0.0.1" + raw
    candidate = raw if "://" in raw else "http://" + raw
    parsed = urllib.parse.urlparse(candidate)
    try:
        port = parsed.port
    except ValueError as exc:
        raise EdgeError("CrowdSec local API listen address is invalid") from exc
    if (
        parsed.scheme not in {"http", "https"}
        or parsed.hostname not in {"127.0.0.1", "localhost", "::1"}
        or port is None
        or not 1 <= port <= 65535
        or parsed.username is not None
        or parsed.password is not None
        or parsed.path not in {"", "/"}
        or parsed.params
        or parsed.query
        or parsed.fragment
    ):
        raise EdgeError("CrowdSec local API must listen on a local loopback address")
    host = f"[{parsed.hostname}]" if parsed.hostname == "::1" else parsed.hostname
    return f"{parsed.scheme}://{host}:{port}"


def setup_crowdsec(
    *,
    paths: EdgePaths = EdgePaths(),
    runner: Runner = run_command,
    policy_path: Path | None = None,
) -> None:
    if os.geteuid() != 0 and paths == EdgePaths():
        raise EdgeError("vwctl crowdsec setup must run as root")
    installer: Path | None = None
    try:
        installer = _download_installer()
        _command(runner, ["/bin/sh", str(installer)], "CrowdSec repository setup")
    finally:
        if installer is not None:
            installer.unlink(missing_ok=True)
    _command(runner, ["apt-get", "update"], "apt metadata refresh")
    install_env = _package_install_env()
    if policy_path is None:
        policy_path = POLICY_RC_D if paths == EdgePaths() else paths.acquisition.parent / ".policy-rc.d"

    # The firewall-bouncer package ships INPUT+FORWARD defaults and package
    # scripts call systemctl directly. Establish the INPUT-only merge override
    # before apt and keep SYSTEMD_OFFLINE scoped to the apt child so neither
    # CrowdSec nor either bouncer can actually start during package configure.
    _write_root_file(
        _firewall_local_path(paths),
        firewall_bouncer_bootstrap_local_text(),
        0o600,
    )

    install_error: EdgeError | None = None
    try:
        with _suppress_package_service_starts(policy_path):
            _apt_command(
                runner,
                [
                    "apt-get",
                    "install",
                    "-y",
                    "crowdsec",
                    "crowdsec-cloudflare-worker-bouncer",
                    "crowdsec-firewall-bouncer-nftables",
                    "logrotate",
                ],
                "CrowdSec package installation",
                env=install_env,
            )
    except EdgeError as exc:
        install_error = exc

    containment_errors = _contain_package_bouncers(runner)
    if install_error is not None:
        if containment_errors:
            raise EdgeError(
                f"{install_error}; package service containment also failed: "
                + "; ".join(containment_errors)
            ) from install_error
        raise install_error
    if containment_errors:
        raise EdgeError("package service containment failed: " + "; ".join(containment_errors))

    _command(runner, ["systemctl", "stop", CROWDSEC_SERVICE], "CrowdSec stop before source restriction")
    _command(runner, ["cscli", "collections", "remove", "--all"], "CrowdSec collection reset")
    _remove_cscli_setup_acquisitions(paths)
    _assert_acquisition_scope(paths)
    _command(runner, ["cscli", "hub", "update"], "CrowdSec Hub metadata refresh")
    for collection in CROWDSEC_COLLECTIONS:
        _command(
            runner,
            ["cscli", "collections", "install", collection],
            f"CrowdSec collection installation ({collection})",
        )
    vaultwarden_log = _vaultwarden_log_path(paths)
    _prepare_vaultwarden_log(vaultwarden_log)
    _write_root_file(
        paths.acquisition,
        acquisition_text(paths.caddy_log, vaultwarden_log),
        0o600,
    )
    _write_root_file(_logrotate_path(paths), vaultwarden_logrotate_text(vaultwarden_log), 0o644)
    _write_root_file(paths.bouncer_dropin, bouncer_dropin_text(paths.remediation_config), 0o644)
    _unlink_state(paths.remediation_start_token, "CrowdSec remediation start token")
    _unlink_state(paths.fail_open_confirmation, "CrowdSec Fail Open confirmation")
    _command(runner, ["systemctl", "daemon-reload"], "systemd reload")
    _command(runner, ["systemctl", "enable", "--now", CROWDSEC_SERVICE], "CrowdSec enable/start")
    _command(runner, ["systemctl", "restart", CROWDSEC_SERVICE], "CrowdSec restart")
    firewall_key = _create_lapi_bouncer_key(runner, FIREWALL_BOUNCER_ID, "host firewall remediation")
    _write_root_file(
        _firewall_local_path(paths),
        firewall_bouncer_local_text(api_key=firewall_key, lapi_url=_local_lapi_url(runner)),
        0o600,
    )
    if not _firewall_boundary_healthy(paths, runner, require_live=False):
        raise EdgeError(
            "CrowdSec firewall bouncer effective configuration is not valid INPUT-only nftables policy"
        )
    _command(
        runner,
        ["systemctl", "enable", "--now", FIREWALL_BOUNCER_SERVICE],
        "CrowdSec firewall bouncer enable/start",
    )
    if not _firewall_boundary_healthy(paths, runner, require_live=True):
        containment = _contain_package_bouncers(runner)
        suffix = f"; disable/stop also failed: {'; '.join(containment)}" if containment else ""
        raise EdgeError(
            "CrowdSec firewall bouncer live nftables ownership is not exactly host INPUT"
            + suffix
        )


